# A referral code is always a User.share_code: 8 uppercase alphanumeric
# chars, generated by subscription_service.generate_share_code(). Anything
# else (wrong length, path-y chars, quotes, ...) can never match a real
# code, so it's rejected here — before it reaches a query or a template —
# rather than treated as merely "not found".
_REFERRAL_CODE_RE = re.compile(r"^[A-Z0-9]{8}$")


def _normalise_referral_code(raw: str | None) -> str | None:
    """Normalise a user-submitted referral code to the canonical share_code
    format, or return None when it can't possibly be valid.

    Callers must treat None exactly like "no such referrer" (the same
    invalid-code state already used for a well-formed but unknown code) and
    must never pass the raw, un-normalised value to a template.
    """
    if not raw:
        return None
    candidate = raw.strip().upper()
    if not _REFERRAL_CODE_RE.fullmatch(candidate):
        return None
    return candidate


@router.post("/referrals/claim-from-invite", response_class=HTMLResponse)
async def claim_referral_from_invite(
    request: Request,
    referral_code: str = Form(...),
    db: AsyncSession = Depends(get_db),
    current_user: User | None = Depends(get_current_user_from_cookie),
):
    """Claim referral bonus after accepting a circle invite"""
    if current_user is None:
        # Cookie expired between the accept and the claim tap — the
        # dependency returns None rather than raising, so guard here
        # instead of 500ing on current_user.id below.
        return HTMLResponse(
            content='<div class="alert alert-error">Your session expired. '
            "Please log in again to claim your free month.</div>"
        )
    code = _normalise_referral_code(referral_code)
    if not code:
        return HTMLResponse(
            content='<div class="alert alert-error">Unable to apply referral.</div>'
        )
    referrer = await referral_service.get_referrer_by_code(db, code)

    if not referrer or referrer.id == current_user.id:
        return HTMLResponse(
            content='<div class="alert alert-error">Unable to apply referral.</div>'
        )

    if await referral_service.has_existing_referral(db, current_user.id):
        return HTMLResponse(
            content='<div class="alert alert-info">You\'ve already used a referral code.</div>'
        )

    referral = await referral_service.claim_referral(
        db, referrer, current_user, code
    )
    subtitle = "Your referral credit has been applied."
    if referral.referrer_credit_applied:
        subtitle += " Your friend got a free month too."

    return HTMLResponse(
        content=f"""
        <div class="card fade-in">
            <div class="text-center">
                <svg class="empty-icon" style="stroke: var(--success); opacity: 1;" fill="none" viewBox="0 0 24 24">
                    <path stroke-linecap="round" stroke-linejoin="round" stroke-width="2" d="M9 12l2 2 4-4m6 2a9 9 0 11-18 0 9 9 0 0118 0z" />
                </svg>
                <h2 class="card-title">You got 30 days free!</h2>
                <p class="text-muted">
                    {subtitle}
                </p>
                <div class="mt-lg">
                    <a href="/circles" class="btn btn-primary">
                        View All Circles
                    </a>
                </div>
            </div>
        </div>
        """
    )


@router.post("/referrals/request-otp", response_class=HTMLResponse)
async def referral_request_otp(
    request: Request,
    phone_number: str = Form(...),
    full_phone_number: str = Form(None),
    # Form("") not Form(...): the invalid-code state re-renders the form with
    # referral_code="", and FastAPI treats "" as missing for a required Form
    # field — a re-submit must reach the invalid-code state, never a 422.
    referral_code: str = Form(""),
    is_resend: bool = Form(False),
    force_resend: bool = Form(False),
    keep_otp_visible: bool = Form(False),
    current_phone: str = Form(None),
    db: AsyncSession = Depends(get_db),
):
    """Request OTP for referral signup"""
    code = _normalise_referral_code(referral_code)
    if not code:
        # Same invalid-code state as an unknown-but-well-formed code
        # (referral_verify_otp's "Invalid referral code") — never echo the
        # raw value back into the template.
        return templates.TemplateResponse(
            request,
            "fragments/referral_auth_form.html",
            {
                "request": request,
                "phone_value": phone_number,
                "referral_code": "",
                "error_message": "Invalid referral code",
                "show_otp": False,
            },
        )

    phone_to_format = full_phone_number if full_phone_number else phone_number
    formatted_phone = format_to_e164(phone_to_format)
    if not formatted_phone:
        return templates.TemplateResponse(
            request,
            "fragments/referral_auth_form.html",
            {
                "request": request,
                "phone_value": phone_to_format,
                "referral_code": code,
                "error_message": "Please enter a valid phone number",
                "show_otp": False,
            },
        )

    if current_phone and current_phone == formatted_phone:
        resend_wait_seconds = await otp_service.get_resend_wait_seconds(
            db, formatted_phone
        )
        display_phone = format_for_display(formatted_phone)
        return templates.TemplateResponse(
            request,
            "fragments/referral_auth_form.html",
            {
                "request": request,
                "phone_number": formatted_phone,
                "phone_value": get_phone_display_value(formatted_phone),
                "display_phone": display_phone,
                "referral_code": code,
                "show_otp": True,
                "resend_wait_seconds": resend_wait_seconds,
            },
        )

    success, message = await otp_service.send_otp(
        db, formatted_phone, force_resend=(is_resend or force_resend)
    )

    resend_wait_seconds = await otp_service.get_resend_wait_seconds(db, formatted_phone)
    display_phone = format_for_display(formatted_phone)

    if not success:
        return templates.TemplateResponse(
            request,
            "fragments/referral_auth_form.html",
            {
                "request": request,
                "phone_number": formatted_phone,
                "phone_value": get_phone_display_value(formatted_phone),
                "display_phone": display_phone,
                "referral_code": code,
                "error_message": message,
                "show_otp": keep_otp_visible or is_resend,
                "resend_wait_seconds": resend_wait_seconds,
            },
        )

    return templates.TemplateResponse(
        request,
        "fragments/referral_auth_form.html",
        {
            "request": request,
            "phone_number": formatted_phone,
            "phone_value": get_phone_display_value(formatted_phone),
            "display_phone": display_phone,
            "referral_code": code,
            "show_otp": True,
            "resend_wait_seconds": resend_wait_seconds,
        },
    )


@router.post("/referrals/verify-otp", response_class=HTMLResponse)
async def referral_verify_otp(
    request: Request,
    phone_number: str = Form(...),
    otp_code: str = Form(...),
    # Form(""): see referral_request_otp — an empty code is the invalid-code
    # state, not a 422.
    referral_code: str = Form(""),
    db: AsyncSession = Depends(get_db),
):
    """Verify OTP and auto-apply referral code"""
    # Normalise once at entry — only this value is ever passed to a
    # template or a query; an unparseable code renders the same
    # "Invalid referral code" state used below for a well-formed but
    # unknown one, never the raw submitted string.
    code = _normalise_referral_code(referral_code)

    success, message = await otp_service.verify_otp(db, phone_number, otp_code)

    if not success:
        display_phone = format_for_display(phone_number)
        return templates.TemplateResponse(
            request,
            "fragments/referral_auth_form.html",
            {
                "request": request,
                "phone_number": phone_number,
                "phone_value": get_phone_display_value(phone_number),
                "display_phone": display_phone,
                "referral_code": code or "",
                "error_message": message,
                "show_otp": True,
                "resend_wait_seconds": 0,
            },
        )

    formatted_phone = format_to_e164(phone_number)
    if not formatted_phone:
        return HTMLResponse(
            content='<div class="alert alert-error">Invalid phone number format</div>'
        )

    # Mark phone number as verified
    phone_rec, _ = await crud_phone_number.get_or_create(db, number=formatted_phone)
    if not phone_rec.verified:
        await crud_phone_number.mark_verified(db, phone=phone_rec)

    user = await crud_user.get_by_phone(db, phone_number=formatted_phone)
    if not user:
        user_create = UserCreate(phone_number=formatted_phone, full_name=None)
        user = await crud_user.create(db, obj_in=user_create)
        from app.services import subscription_service

        user.share_code = subscription_service.generate_share_code()
        await db.commit()
        await db.refresh(user)

    from app.services import subscription_service

    await subscription_service.resolve_pending_gifts(db, formatted_phone, user.id)

    referral_applied = False
    referral_error = None

    referrer = await referral_service.get_referrer_by_code(db, code) if code else None

    if code and referrer and referrer.id != user.id:
        if not await referral_service.has_existing_referral(db, user.id):
            await referral_service.claim_referral(db, referrer, user, code)
            referral_applied = True
        else:
            referral_error = "You've already used a referral code"
    elif referrer and referrer.id == user.id:
        referral_error = "You can't use your own referral code"
    else:
        referral_error = "Invalid referral code"

    return HTMLResponse(
        content=f"""
        <div class="text-center fade-in">
            <div class="success-icon">
                <svg fill="none" viewBox="0 0 24 24">
                    <path stroke-linecap="round" stroke-linejoin="round" d="M5 13l4 4L19 7" />
                </svg>
            </div>
            {'<h2 style="color: #2C3E50; margin-bottom: 10px;">Welcome! You got 30 days free</h2>' if referral_applied else '<h2 style="color: #2C3E50; margin-bottom: 10px;">Account Verified</h2>'}
            {'<p class="text-muted" style="margin-bottom: 30px;">Your referral credit has been applied</p>' if referral_applied else f'<p class="text-muted" style="margin-bottom: 30px;">{referral_error or ""}</p>'}

            <div style="margin-top: 20px;">
                <p style="font-weight: 600; color: #2C3E50; margin-bottom: 15px;">Get the app to start staying safe</p>
                <a href="https://apps.apple.com/app/id6787024225"
                   style="display: inline-block; margin: 8px; padding: 14px 28px; background: linear-gradient(135deg, #14B8A6, #0D9488); color: white; border-radius: 100px; text-decoration: none; font-weight: 700; box-shadow: 0 4px 15px rgba(20, 184, 166, 0.35);">
                    Download for iPhone
                </a>
                <a href="https://play.google.com/store/apps/details?id=com.madeithome.app"
                   style="display: inline-block; margin: 8px; padding: 14px 28px; background: linear-gradient(135deg, #14B8A6, #0D9488); color: white; border-radius: 100px; text-decoration: none; font-weight: 700; box-shadow: 0 4px 15px rgba(20, 184, 166, 0.35);">
                    Download for Android
                </a>
            </div>
        </div>
        """
    )
